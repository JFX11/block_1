"""
Функция для подсчета кол-ва слова в строке.
"""

import string


def count_word(text):
    """
    Функция принимает аргумент - строку. Возвращает словарь в формате {слово: кол-во повторений}

    Функция проверяет что передаваемый аргумент является строкой, если нет
    то падает исключение TypeError. Так-же проверяет, что текст не пустой.
    Пустой текст - это текст в котором не содержится никаких символов.
    Если текст пустой, падает исключение TypeError

    С помощью for и метода строк split(), происходит перебор слов. Во время перебора
    каждое слово проверяется на содержание символов пунктуации или иных других. Они отсеиваются
    и в результат попадает отфильтрованное слово. Слово может содержать цифру или цифры.
    Если по итого перебора и фильтрации текста, словарь остается пустым, падает исключение
    что строка не содержала никаких слов.
    Словом счиатается набор связанных букв с длиной от 2 символов.
    """
    if type(text) is not str:
        raise TypeError("Аргумент не является строкой")
    if not text.strip():
        raise ValueError("Пустая строка")

    dict_words = {}
    for word in text.lower().split():
        filtered_word = word.strip(string.punctuation + "«»—–…“”‘’№")
        if len(filtered_word) >= 2:
            dict_words[filtered_word] = dict_words.get(filtered_word, 0) + 1

        if not dict_words:
            raise ValueError("Передаваемая строка не содержит слов")
    return dict_words


print(count_word("а"))

