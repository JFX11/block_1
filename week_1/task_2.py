import string


def count_word(text):
    dict_words = {}
    for word in text.lower().split():
        filtered_word = word.strip(string.punctuation + string.octdigits)

        if len(filtered_word) > 1:
            if dict_words.get(filtered_word):
                dict_words[filtered_word] += 1
            else:
                dict_words[filtered_word] = 1

    return dict_words


