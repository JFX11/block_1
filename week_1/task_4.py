"""
Данная программа предназначена для чтения файла, считывания строк и записи кол-ва строк
в отдельный файл.
"""


def count_lines(file_name):
    """
    Функция подсчета строк из файла.
    Функция принимает 1 аргумент(имя файла в формате str)
    Если аргумент не является строкой, то падает исключение TypeError
    Функция должна вернуть целое число строк, если в файле есть строки и
    вернуть 0, если файл пустой.
    Считывание строк происходит с помощью цикла for. Т.к file считается
    итерируемым объектом, мы можем пройтись по всем строкам которые есть в файле.
    Окончание строки определяется символом '\n'. Но, даже если его не будет в файле,
    но будет хоть 1 символ, это будет считаться за строку.
    Если файл не будет найден в каталоге, то отобразится ошибка FileNotFoundError
    """
    if type(file_name) is not str:
        raise TypeError(f"Передаваемый аргумент '{file_name}' не является строкой")

    with open(file_name, "r", encoding="utf-8") as file:
        number_lines = 0
        for line in file:
            number_lines += 1

    return number_lines


#  count_lines(1) - TypeError: Передаваемый аргумент '1' не является строкой
#  file.txt(файл пустой) - 0
#  Файла нет - FileNotFoundError
#  ' ' - 1
#  'x\n\n' - 2
#  \n\n\n - 3
#  10 строк 'строка' - 10
#  'x' - 1


def write_count_lines(file_name, number_lines):
    """
    Функция для создания файла и записи целого неотрицательного числа
    Функция принимает 2 аргумента, file_name - имя файла, который нужно создать и
    целое число(результат функции count_lines).
    Если передается аргумент(file_name) не с типом str - падает исключение TypeError
    Если передается аргумент(number_lines) отрицательное целое число - ValueError
    Если не число с типом int - TypeError
    Функция ничего не возвращает. Только создает файл и записывает туда аргумент number_lines
    Если файл уже присутствует в системе, то функция перезапишет результат, т.к режим
    'w' - перезаписывает результат в файле. Результат записывает с '\n', чтобы в консоли
    результат не прилипал к строке ввода
    """
    if type(file_name) is not str:
        raise TypeError(f"Файл не создан. Некорректное имя файла: '{file_name}'")
    if type(number_lines) is not int:
        raise TypeError(
            f"Запись прервалась. Передаваемый аргумент '{number_lines}' не является целым числом"
        )
    if number_lines < 0:
        raise ValueError(
            f"Запись прервалась. Передаваемый аргумент '{number_lines}' должен быть неотрицательным числом"
        )

    with open(file_name, "w", encoding="utf-8") as file:
        number_lines_str = str(number_lines) + "\n"
        file.write(number_lines_str)


write_count_lines("res.txt", count_lines(1))


